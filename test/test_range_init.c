// ── 測試：GNU 陣列範圍初始化 [lo ... hi] = val ──

#include <stdio.h>

int main() {

    // ── 測試 1：基本範圍，全部設成同一個值 ──
    int a[10] = { [0 ... 9] = -1 };
    printf("a[0]=%d a[5]=%d a[9]=%d\n", a[0], a[5], a[9]);
    // 期望：a[0]=-1 a[5]=-1 a[9]=-1

    // ── 測試 2：部分範圍 + 其餘為 0 ──
    int b[8] = { [2 ... 5] = 99 };
    printf("b[0]=%d b[2]=%d b[5]=%d b[7]=%d\n", b[0], b[2], b[5], b[7]);
    // 期望：b[0]=0 b[2]=99 b[5]=99 b[7]=0

    // ── 測試 3：多段範圍 ──
    int c[10] = { [0 ... 3] = 1, [4 ... 7] = 2, [8 ... 9] = 3 };
    printf("c[0]=%d c[3]=%d c[4]=%d c[7]=%d c[8]=%d c[9]=%d\n",
           c[0], c[3], c[4], c[7], c[8], c[9]);
    // 期望：c[0]=1 c[3]=1 c[4]=2 c[7]=2 c[8]=3 c[9]=3

    // ── 測試 4：範圍 + 單點 designated 混合 ──
    int d[8] = { [0 ... 7] = 0, [3] = 42, [6] = 99 };
    printf("d[0]=%d d[3]=%d d[6]=%d d[7]=%d\n", d[0], d[3], d[6], d[7]);
    // 期望：d[0]=0 d[3]=42 d[6]=99 d[7]=0

    // ── 測試 5：範圍 + 後接 plain initializer（autoIdx 延續）──
    int e[6] = { [0 ... 2] = 10, 20, 30 };
    printf("e[0]=%d e[1]=%d e[2]=%d e[3]=%d e[4]=%d e[5]=%d\n",
           e[0], e[1], e[2], e[3], e[4], e[5]);
    // 期望：e[0]=10 e[1]=10 e[2]=10 e[3]=20 e[4]=30 e[5]=0

    // ── 測試 6：char 陣列範圍初始化 ──
    char f[6] = { [0 ... 5] = 'A' };
    printf("f[0]=%c f[3]=%c f[5]=%c\n", f[0], f[3], f[5]);
    // 期望：f[0]=A f[3]=A f[5]=A

    // ── 測試 7：單點 designated（原功能，確認不受影響）──
    int g[5] = { [1] = 11, [3] = 33 };
    printf("g[0]=%d g[1]=%d g[2]=%d g[3]=%d g[4]=%d\n",
           g[0], g[1], g[2], g[3], g[4]);
    // 期望：g[0]=0 g[1]=11 g[2]=0 g[3]=33 g[4]=0

    return 0;
}
