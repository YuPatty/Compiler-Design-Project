// ── 準備用來測試的結構體與函式 ──
struct Node {
    int id;
    float score;
};

int multiply(int a, int b) {
    return a * b;
}

int main() {
    printf("=== Starting Semantic Analysis Test ===\n");

    // ==========================================
    // 1. 測試：重複宣告變數 (Redeclared Variable)
    // ==========================================
    int a = 10;
    float a = 3.14; // 💣 故意重複宣告 a

    // ==========================================
    // 2. 測試：未宣告的變數 (Undeclared Variable)
    // ==========================================
    b = 20;         // 💣 b 從未宣告過
    int c = b + 5;  // 💣 讀取未宣告的變數

    // ==========================================
    // 3. 測試：等號兩邊型別不同 (這會觸發「隱式轉型」，不該報錯)
    // ==========================================
    float f_val = 100;    // int -> float (會產生 sitofp)
    int i_val = 3.14159;  // float -> int (會產生 fptosi)
    char ch = 65;         // int -> char (會產生 trunc)
    int i_from_ch = ch;   // char -> int (會產生 sext)

    // ==========================================
    // 4. 測試：結構體成員檢查 (Struct Member Check)
    // ==========================================
    struct Node* ptr = (struct Node*)malloc(16);
    ptr->id = 1;          // 合法
    ptr->fake_field = 10; // 💣 結構體裡根本沒有 fake_field

    int not_a_ptr = 5;
    not_a_ptr->id = 2;    // 💣 not_a_ptr 是整數，不能用 ->

    struct Node myNode;
    myNode.score = 99.9;  // 合法
    myNode.wrong = 0;     // 💣 結構體裡根本沒有 wrong，且 . 運算子也該抓出來

    // ==========================================
    // 5. 測試：函式引數數量檢查 (Function Arg Count)
    // ==========================================
    multiply(5);          // 💣 參數太少 (預期 2 個，只給 1 個)
    multiply(1, 2, 3);    // 💣 參數太多 (預期 2 個，給了 3 個)

    // ==========================================
    // 6. 測試：函式引數型別檢查 (隱式轉型)
    // ==========================================
    // 傳入 float，但 multiply 預期 int，編譯器應該默默轉型不報錯
    int ans = multiply(3.14, 2.99); 

    // ==========================================
    // 7. 測試：內建函式的防呆檢查
    // ==========================================
    strcpy("hello");      // 💣 strcpy 規定要 2 個參數
    free(12345);          // 💣 free 預期要收到指標，而不是整數

    printf("=== Test Finished ===\n");
    return 0;
}