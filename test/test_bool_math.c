// 測試布林/關係運算式的隱式整數升級與無分支數學運算
// ============================================================
#include <stdio.h>

int main(void) {
    int a = 2;
    int b = 5;
    int c = 10;
    int d = 20;

    printf("=== Branchless Math Test ===\n");

    // 1. 測試 (a == 2) * 100
    // 條件成立時：1 * 100 = 100
    printf("(a == 2) * 100 = %d\n", (a == 2) * 100);
    // 條件不成立時：0 * 100 = 0
    printf("(a == 3) * 100 = %d\n", (a == 3) * 100);

    // 2. 測試 (a < b) * (c < d) (相當於邏輯 AND，但不使用 &&)
    // 兩者皆成立：1 * 1 = 1
    printf("(a < b) * (c < d) = %d\n", (a < b) * (c < d));
    // 左邊不成立：0 * 1 = 0
    printf("(b < a) * (c < d) = %d\n", (b < a) * (c < d));

    // 3. 測試 (a == 2) / 1
    // 條件成立時：1 / 1 = 1
    printf("(a == 2) / 1 = %d\n", (a == 2) / 1);
    // 條件不成立時：0 / 1 = 0
    printf("(a == 3) / 1 = %d\n", (a == 3) / 1);

    return 0;
}